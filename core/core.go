// Package core holds the types shared by every Ackhammer package.
//
// It has no logic and no dependency outside the standard library, so that
// fault, probe, invariant and the runner can all import it without cycles.
// The root package re-exports these types under the ackhammer name.
package core

import (
	"context"
	"errors"
	"math/rand/v2"
	"time"
)

// Message is a traceable message published by Ackhammer.
type Message struct {
	ID          string            // unique, generated by Ackhammer
	Key         string            // ordering key
	Traceparent string            // W3C Trace Context
	Payload     []byte            // opaque body
	Attributes  map[string]string // extra metadata
}

// Handler processes one message. A nil error asks the target to ack it,
// any other error asks the target to nack it.
type Handler func(ctx context.Context, msg Message) error

// Target is the system under test: a broker, a publisher and a consumer.
type Target interface {
	Name() string
	Publish(ctx context.Context, msg Message) error
	// Consume delivers messages to h until ctx is done or the consumer is
	// stopped, then returns. It may be called again after it returns.
	Consume(ctx context.Context, h Handler) error
	// Close releases everything the target holds (publisher included).
	Close(ctx context.Context) error
}

// Restartable targets can recreate their consumer. Required by RestartConsumer.
type Restartable interface {
	Target
	// Restart is called while no Consume is running. It recreates the
	// consumer with the same configuration; the next Consume uses it.
	Restart(ctx context.Context) error
}

// ConsumerStopper targets can stop consuming gracefully without closing the
// publisher. Required by GracefulStop.
type ConsumerStopper interface {
	Target
	// StopConsuming asks the running Consume to finish in-flight messages
	// and return.
	StopConsuming(ctx context.Context) error
}

// PoisonInspector targets can list the messages routed to the poison queue.
// Required by the PoisonRouted invariant.
type PoisonInspector interface {
	Target
	PoisonedIDs(ctx context.Context) ([]string, error)
}

// Killer targets run their consumer in a separate process that can be
// killed abruptly. Required by KillProcess.
type Killer interface {
	Target
	// Kill stops the consumer process at once (SIGKILL): no ack, no nack,
	// no cleanup. The running Consume then returns.
	Kill() error
}

// ErrUnsupported is returned when a fault needs a capability the target
// does not implement.
var ErrUnsupported = errors.New("ackhammer: target does not support this fault")

// Delivery is the delivery mode a consumer claims to provide.
type Delivery string

const (
	AtLeastOnce     Delivery = "at_least_once"
	AtMostOnce      Delivery = "at_most_once"
	EffectivelyOnce Delivery = "effectively_once"
)

// Ordering is the ordering a consumer claims to provide.
type Ordering string

const (
	NoOrder Ordering = "no_order"
	PerKey  Ordering = "per_key"
)

// Unlimited disables the MaxRedeliveries check.
const Unlimited = -1

// Guarantee is what the user claims their consumer provides.
type Guarantee struct {
	Delivery Delivery
	Ordering Ordering
	// MaxRedeliveries is the number of deliveries allowed after a message
	// was handled successfully. 0 means none, Unlimited disables the check.
	MaxRedeliveries int
	// RedeliveryWithin is the maximum delay between a failure (handler
	// error or injected fault) and the next delivery. 0 disables the check.
	RedeliveryWithin time.Duration
	// PoisonAfter is the number of failures after which a message must be
	// in the poison queue. 0 means there is no poison queue.
	PoisonAfter int
}

// WithMaxRedeliveries returns a copy of g with MaxRedeliveries set.
func (g Guarantee) WithMaxRedeliveries(n int) Guarantee { g.MaxRedeliveries = n; return g }

// WithRedeliveryWithin returns a copy of g with RedeliveryWithin set.
func (g Guarantee) WithRedeliveryWithin(d time.Duration) Guarantee { g.RedeliveryWithin = d; return g }

// WithPoisonAfter returns a copy of g with PoisonAfter set.
func (g Guarantee) WithPoisonAfter(n int) Guarantee { g.PoisonAfter = n; return g }

// WithOrdering returns a copy of g with Ordering set.
func (g Guarantee) WithOrdering(o Ordering) Guarantee { g.Ordering = o; return g }

// Fault is anything that can be injected during a scenario. A fault is
// either a HandlerFault or a TimedFault.
type Fault interface {
	Name() string
}

// HandlerFault runs inside the probe, before the user handler.
type HandlerFault interface {
	Fault
	// Plan is called once before the run, with the scenario's seeded
	// source, so that random selection is reproducible.
	Plan(r *rand.Rand, msgs []Message)
	// Applies reports whether the fault fires for this delivery.
	// attempt starts at 1.
	Applies(msg Message, attempt int) bool
	// Apply runs the fault. A non-nil error fails the delivery without
	// calling the user handler.
	Apply(ctx context.Context, msg Message) error
}

// TimedFault fires once, At after the first message is published.
type TimedFault interface {
	Fault
	At() time.Duration
	Inject(ctx context.Context, c Controller) error
}

// Controller lets timed faults act on the running consumer. Every method
// breaks the consumer and then resumes consuming (recovery phase).
//
// Before the run, faults are injected once against a dry-run Controller that
// performs nothing: a fault must return ErrUnsupported from Inject when the
// target lacks a capability it needs, so the run fails before it starts.
type Controller interface {
	// Target is the target under test.
	Target() Target
	// Cancel cancels the context given to Consume.
	Cancel(ctx context.Context) error
	// Stop calls ConsumerStopper.StopConsuming.
	Stop(ctx context.Context) error
	// Restart cancels Consume and calls Restartable.Restart.
	Restart(ctx context.Context) error
	// Break runs action, which is expected to make Consume return on its
	// own (a crash, a closed connection…), waits for Consume to return,
	// then resumes consuming.
	Break(ctx context.Context, action func(context.Context) error) error
}

// Scenario is one fault-injection test.
type Scenario struct {
	Name     string
	Messages int      // number of messages to publish (default 10)
	Keys     []string // ordering keys, assigned round-robin (default 4 keys)
	// Handler is the user's consumer logic. It runs behind the probe.
	// nil means a handler that always succeeds.
	Handler Handler
	Faults  []Fault
	Expect  Guarantee
	// Seed makes the run reproducible. 0 picks a random seed, printed in
	// the report. The ACKHAMMER_SEED environment variable overrides it.
	Seed int64
	// DrainTimeout bounds the wait for every message to be handled
	// (default 30s).
	DrainTimeout time.Duration
	// Settle is how long the run keeps observing after the drain, to catch
	// late duplicates (default 300ms).
	Settle time.Duration
}

type effectKey struct{}

// WithEffectSink returns a context that routes RecordEffect calls to sink.
// The probe sets it; users do not need it.
func WithEffectSink(ctx context.Context, sink func(effect string)) context.Context {
	return context.WithValue(ctx, effectKey{}, sink)
}

// RecordEffect records a business effect (for example "order 42 charged")
// for the EffectOnce invariant. Call it from the handler with the context
// the handler received. Outside a scenario it does nothing.
func RecordEffect(ctx context.Context, effect string) {
	if sink, ok := ctx.Value(effectKey{}).(func(string)); ok {
		sink(effect)
	}
}
