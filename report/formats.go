// failingIDs returns the messages shown in timelines, at most MaxTimelines.
func (r *Report) failingIDs() []string {
	var ids []string
	seen := map[string]bool{}
	for _, res := range r.Results {
		if res.Status != invariant.Fail {
			continue
		}
		for _, id := range res.MsgIDs {
			if len(ids) == MaxTimelines {
				return ids
			}
			if !seen[id] {
				seen[id] = true
				ids = append(ids, id)
			}
		}
	}
	return ids
}

// JUnit XML

type junitSuites struct {
	XMLName xml.Name     `xml:"testsuites"`
	Suites  []junitSuite `xml:"testsuite"`
}

type junitSuite struct {
	Name     string      `xml:"name,attr"`
	Tests    int         `xml:"tests,attr"`
	Failures int         `xml:"failures,attr"`
	Skipped  int         `xml:"skipped,attr"`
	Time     string      `xml:"time,attr"`
	Cases    []junitCase `xml:"testcase"`
	Out      string      `xml:"system-out,omitempty"`
}

type junitCase struct {
	Name      string        `xml:"name,attr"`
	ClassName string        `xml:"classname,attr"`
	Failure   *junitMessage `xml:"failure,omitempty"`
	Skipped   *junitMessage `xml:"skipped,omitempty"`
}

type junitMessage struct {
	Message string `xml:"message,attr"`
	Body    string `xml:",chardata"`
}

// JUnit renders the reports as one JUnit XML document: one test suite per
// scenario, one test case per invariant.
func JUnit(reports ...*Report) ([]byte, error) {
	var doc junitSuites
	for _, r := range reports {
		s := junitSuite{
			Name: r.Scenario,
			Time: fmt.Sprintf("%.3f", r.Duration.Seconds()),
			Out:  fmt.Sprintf("seed %d, target %s\n%s", r.Seed, r.Target, r.Replay),
		}
		for _, res := range r.Results {
			c := junitCase{Name: res.Name, ClassName: "ackhammer." + r.Scenario}
			switch res.Status {
			case invariant.Fail:
				s.Failures++
				var body strings.Builder
				for _, id := range res.MsgIDs[:min(len(res.MsgIDs), MaxTimelines)] {
					body.WriteString(r.Timeline(id))
				}
				if r.Replay != "" {
					body.WriteString("\nReplay: " + r.Replay + "\n")
				}
				c.Failure = &junitMessage{Message: res.Summary, Body: body.String()}
			case invariant.Skip:
				s.Skipped++
				c.Skipped = &junitMessage{Message: res.Summary}
			}
			s.Tests++
			s.Cases = append(s.Cases, c)
		}
		doc.Suites = append(doc.Suites, s)
	}
	out, err := xml.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	return append([]byte(xml.Header), append(out, '\n')...), nil
}

// Markdown for GitHub issues

// Issue renders the report as Markdown ready to paste into a GitHub issue:
// environment, scenario, expected vs actual, timelines and the repro
// command.
func (r *Report) Issue() string {
	var b strings.Builder
	fmt.Fprintf(&b, "### Ackhammer: `%s` on `%s`\n\n", r.Scenario, r.Target)

	if len(r.Environment) > 0 {
		b.WriteString("**Environment**\n\n| | |\n|---|---|\n")
		for _, k := range slices.Sorted(maps.Keys(r.Environment)) {
			fmt.Fprintf(&b, "| %s | `%s` |\n", k, r.Environment[k])
		}
		b.WriteString("\n")
	}

	b.WriteString("**Expected vs actual**\n\n| Invariant | Result | Details |\n|---|---|---|\n")
	for _, res := range r.Results {
		if res.Status == invariant.Skip {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", res.Name, res.Status, res.Summary)
	}

	if ids := r.failingIDs(); len(ids) > 0 {
		b.WriteString("\n**Timelines**\n\n```\n")
		for _, id := range ids {
			b.WriteString(r.Timeline(id))
		}
		b.WriteString("```\n")
	}
	fmt.Fprintf(&b, "\n**Reproduce** (seed %d)\n\n", r.Seed)
	if r.Replay != "" {
		fmt.Fprintf(&b, "```sh\n%s\n```\n", r.Replay)
	}
	b.WriteString("\n<sub>Generated by [Ackhammer](https://github.com/AristideDongo/ackhammer).</sub>\n")
	return b.String()
}

// HTML

// HTML renders the reports as a self-contained HTML page.
func HTML(w io.Writer, reports ...*Report) error {
	type view struct {
		*Report
		Timelines []string
		Rounded   time.Duration
	}
	var views []view
	for _, r := range reports {
		v := view{Report: r, Rounded: r.Duration.Round(time.Millisecond)}
		for _, id := range r.failingIDs() {
			v.Timelines = append(v.Timelines, r.Timeline(id))
		}
		views = append(views, v)
	}
	var buf bytes.Buffer
	if err := htmlTemplate.Execute(&buf, views); err != nil {
		return err
	}
	_, err := w.Write(buf.Bytes())
	return err
}

